test('real typing can be captured and evaluated on a separate validation segment', async ({ page, request }) => {
  const response = await request.post('/api/notes', { data: { title: 'Typing capture' } })
  const note = await response.json()
  await page.goto(`/?note=${note.id}`)
  await expect(page.getByText('All changes saved', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'The experiment' }).click()
  await page.getByRole('button', { name: 'Capture my typing' }).click()
  await page.getByRole('textbox', { name: 'Note content' }).pressSequentially('A real trace of my own typing.', { delay: 140 })
  await page.getByRole('button', { name: 'The experiment' }).click()
  await page.getByRole('button', { name: /Stop capture/ }).click()
  await page.getByLabel('THE CONNECTION', { exact: true }).selectOption('normal')
  const completed = page.waitForResponse(response => response.url().endsWith('/api/experiments'))
  await page.getByRole('button', { name: /Run the experiment/ }).click()
  const result = await (await completed).json()
  expect(result.source).toBe('recorded')
  expect(result.results[0].scenarios).toHaveLength(2)
  expect(result.results[0].scenarios[0].split).toBe('calibration')
  expect(result.results[0].scenarios[1].split).toBe('validation')
  expect(result.validation_passed).toBe(true)
  await expect(page.locator('.result-number')).toHaveText('0')
})
